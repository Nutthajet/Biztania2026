const daysBefore = (days: number) =>
  new Date(Date.parse(`${DEMO_DATE}T00:00:00Z`) - days * 86400000).toISOString().slice(0, 10);
export const customers: Customer[] = seeds.map((s, i) => ({
  id: `c${i + 1}`,
  companyName: s[0],
  industry: s[1],
  region: s[2],
  purchaseProbability: s[3],
  churnRisk: s[4],
  averageOrderValue: s[5],
  lastPurchaseDate: daysBefore(s[6]),
  reorderCycle: i === 0 ? 30 : 28,
  preferredProducts: s[7],
  salesRep: s[8],
  salesHoursAvailable: 8,
  requiredHours: s[9],
  opportunity: s[10],
}));
export const history: Transaction[] = customers.flatMap((customer, i) =>
  Array.from({ length: 6 }, (_, n) => {
    const product = products.find((p) => p.id === customer.preferredProducts[0])!;
    const quantity = Math.round(
      (customer.averageOrderValue / product.price) * (0.8 + ((i + n) % 5) * 0.05),
    );
    return {
      id: `tx-${i}-${n}`,
      customer: customer.id,
      product: product.id,
      date: daysBefore(seeds[i][6] + n * customer.reorderCycle),
      quantity,
      revenue: quantity * product.price,
      margin: quantity * (product.price - product.cost),
    };
  }),
);
